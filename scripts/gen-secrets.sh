#!/bin/bash
# Generates tisk-ios/Secrets.swift (gitignored) from tisk-ios/.env
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/tisk-ios/.env"
OUT="$ROOT/tisk-ios/Secrets.swift"

if [ ! -f "$ENV_FILE" ]; then
  echo "Missing $ENV_FILE" >&2
  exit 1
fi

get() {
  grep -E "^$1=" "$ENV_FILE" | head -n1 | cut -d= -f2- | sed -e 's/^["'\'']//' -e 's/["'\'']$//' | tr -d '\r'
}

URL="$(get NEXT_PUBLIC_SUPABASE_URL)"
KEY="$(get NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY)"

if [ -z "$URL" ] || [ -z "$KEY" ]; then
  echo "NEXT_PUBLIC_SUPABASE_URL / NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY missing in .env" >&2
  exit 1
fi

cat > "$OUT" <<EOF
// Generated by scripts/gen-secrets.sh from tisk-ios/.env. Do not commit.
enum Secrets {
    static let supabaseURL = "$URL"
    static let supabasePublishableKey = "$KEY"
}
EOF

echo "Wrote $OUT"
